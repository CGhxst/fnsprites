import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { normalizeSourceCatalog, parseSourceCatalog } from './read-source-catalog.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dataPath = path.join(root, 'sprites-data.js');
const outputDirectory = path.join(root, 'src', 'generated');
const outputPath = path.join(outputDirectory, 'sprites.js');
const source = await readFile(dataPath, 'utf8');
const normalizedSource = normalizeSourceCatalog(source);
const sprites = parseSourceCatalog(normalizedSource);
const output = [
    '// Generated from sprites-data.js by scripts/build-catalog-module.mjs.',
    '// Do not edit this file by hand.',
    `export const sprites = ${JSON.stringify(sprites, null, 4)};`,
    '',
].join('\n');

if (source !== normalizedSource) {
    await writeFile(dataPath, normalizedSource, 'utf8');
}
await mkdir(outputDirectory, { recursive: true });
await writeFile(outputPath, output, 'utf8');
console.log(`Generated ${path.relative(root, outputPath)} with ${sprites.length} sprites.`);
